BEGIN;

-- ---------- Login users (Django built-in table) ----------
CREATE TABLE auth_user (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      VARCHAR(128)  NOT NULL,          -- hashed password (pbkdf2), plain text illa
    last_login    TIMESTAMPTZ,
    is_superuser  BOOLEAN       NOT NULL DEFAULT FALSE,
    username      VARCHAR(150)  NOT NULL UNIQUE,
    first_name    VARCHAR(150)  NOT NULL DEFAULT '',
    last_name     VARCHAR(150)  NOT NULL DEFAULT '',
    email         VARCHAR(254)  NOT NULL DEFAULT '',
    is_staff      BOOLEAN       NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    date_joined   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------- API token ----------
CREATE TABLE authtoken_token (
    key      VARCHAR(40)  PRIMARY KEY,
    created  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    user_id  INTEGER      NOT NULL UNIQUE REFERENCES auth_user (id) ON DELETE CASCADE
);

-- ---------- Department ----------
CREATE TABLE portal_department (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    description  TEXT         NOT NULL DEFAULT ''
);

-- ---------- Team (oru department kulla) ----------
CREATE TABLE portal_team (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    department_id  BIGINT       NOT NULL REFERENCES portal_department (id) ON DELETE CASCADE,
    UNIQUE (name, department_id)
);
CREATE INDEX idx_team_department ON portal_team (department_id);

-- ---------- Employee (auth_user oda 1-to-1) ----------
CREATE TABLE portal_employee (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER      NOT NULL UNIQUE REFERENCES auth_user (id) ON DELETE CASCADE,
    employee_id    VARCHAR(20)  NOT NULL UNIQUE,                 -- EMP001 maari
    department_id  BIGINT       REFERENCES portal_department (id) ON DELETE SET NULL,
    team_id        BIGINT       REFERENCES portal_team (id)       ON DELETE SET NULL,
    designation    VARCHAR(100) NOT NULL DEFAULT '',
    joining_date   DATE,
    status         VARCHAR(10)  NOT NULL DEFAULT 'active'   CHECK (status IN ('active', 'inactive')),
    role           VARCHAR(10)  NOT NULL DEFAULT 'employee' CHECK (role   IN ('employee', 'hr', 'admin')),
    phone          VARCHAR(20)  NOT NULL DEFAULT ''
);
CREATE INDEX idx_employee_department ON portal_employee (department_id);
CREATE INDEX idx_employee_team       ON portal_employee (team_id);

-- ---------- Attendance (oru employee ku oru naal ku oru row) ----------
CREATE TABLE portal_attendance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  BIGINT NOT NULL REFERENCES portal_employee (id) ON DELETE CASCADE,
    date         DATE   NOT NULL,
    in_time      TIME,
    out_time     TIME,
    UNIQUE (employee_id, date)
);
CREATE INDEX idx_attendance_employee ON portal_attendance (employee_id);
CREATE INDEX idx_attendance_date     ON portal_attendance (date);

-- ---------- Project ----------
CREATE TABLE portal_project (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(150) NOT NULL,
    description  TEXT         NOT NULL DEFAULT '',
    status       VARCHAR(12)  NOT NULL DEFAULT 'inprogress'
                 CHECK (status IN ('inprogress', 'completed', 'onhold')),
    start_date   DATE,
    end_date     DATE
);

-- ---------- Project <-> Employee (many-to-many) ----------
CREATE TABLE portal_project_employees (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL REFERENCES portal_project  (id) ON DELETE CASCADE,
    employee_id  BIGINT NOT NULL REFERENCES portal_employee (id) ON DELETE CASCADE,
    UNIQUE (project_id, employee_id)
);
CREATE INDEX idx_pe_project  ON portal_project_employees (project_id);
CREATE INDEX idx_pe_employee ON portal_project_employees (employee_id);

COMMIT;
